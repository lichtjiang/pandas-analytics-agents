VISUALIZATION_SYSTEM_PROMPT = """
You are the visualization-design component of a data analysis
system.

Given:

1. The user's original request.
2. The actual DataFrame produced by the SQL query.

Generate a VisualizationSpec describing how the DataFrame
should be plotted.

You MUST choose columns that actually exist in the DataFrame.

Available chart types:

- bar
- line
- scatter
- pie
- histogram
- box

Guidelines:

bar:
    categorical x + numeric y

line:
    ordered/sequential x + numeric y

scatter:
    numeric x + numeric y

pie:
    categorical x + numeric y

histogram:
    numeric x

box:
    categorical x + numeric y

Prefer bar charts for ranking/comparison questions.

Prefer line charts for trends over an ordered dimension.

Prefer scatter plots for relationships between two numerical
variables.

Do not generate Python, matplotlib, or seaborn code.
Generate only the structured VisualizationSpec.
"""


def generate_visualization_spec_node(
    state: VisualizationState,
) -> dict:
    print(f"\ngenerate_visualization_spec_node: {state}")

    df = state["dataframe"]

    context = prepare_dataframe_context(df)

    print(f"\ncontext from prepare_dataframe_context: {context}")

    response = llm.with_structured_output(
        VisualizationSpec
    ).invoke(
        [
            SystemMessage(
                content=VISUALIZATION_SYSTEM_PROMPT
            ),
            HumanMessage(
                content=f"""
User request:

{state["user_question"]}

DataFrame produced by SQL:

{context}
"""
            ),
        ]
    )

    print(f"\ngenerate_visualization_spec_node: response={response}")

    return {
        "visualization_spec": response.model_dump() #response
    }


# ============================================================
#  Validate visualization specification
# ============================================================

def validate_visualization_spec(
    state: VisualizationState,
) -> dict:

    print(f"\nvalidate_visualization_spec: {state}")

    spec = VisualizationSpec.model_validate(state["visualization_spec"])
    df = state["dataframe"]

    columns = set(df.columns)

    if (
        spec.x_column is not None
        and spec.x_column not in columns
    ):
        raise ValueError(
            f"x_column '{spec.x_column}' "
            f"does not exist in DataFrame."
        )

    if (
        spec.y_column is not None
        and spec.y_column not in columns
    ):
        raise ValueError(
            f"y_column '{spec.y_column}' "
            f"does not exist in DataFrame."
        )

    if (
        spec.color_column is not None
        and spec.color_column not in columns
    ):
        raise ValueError(
            f"color_column '{spec.color_column}' "
            f"does not exist in DataFrame."
        )

    # Chart-specific validation.

    if spec.chart_type in {
        "bar",
        "line",
        "scatter",
        "box",
    }:
        if not spec.x_column:
            raise ValueError(
                f"{spec.chart_type} chart requires "
                "x_column."
            )

        if not spec.y_column:
            raise ValueError(
                f"{spec.chart_type} chart requires "
                "y_column."
            )

    if spec.chart_type == "histogram" and not spec.x_column:
        raise ValueError(
            "Histogram requires x_column."
        )

    if spec.chart_type == "pie":
        if not spec.x_column:
            raise ValueError(
                "Pie chart requires x_column."
            )

        if not spec.y_column:
            raise ValueError(
                "Pie chart requires y_column."
            )

    return {}


# ============================================================
#  Deterministic visualization renderer
# ============================================================

outputs = os.environ.get("OUTPUT_DIR", "./outputs")
OUTPUT_DIR = Path(outputs)
OUTPUT_DIR.mkdir(
    exist_ok=True
)


def render_visualization(
    df: pd.DataFrame,
    spec: VisualizationSpec,
) -> str:
    """
    Deterministically render a DataFrame according to a
    VisualizationSpec.

    The LLM never generates plotting code.
    """

    plt.figure(
        figsize=(12, 7)
    )

    chart_type = spec.chart_type

    if chart_type == "bar":

        sns.barplot(
            data=df,
            x=spec.x_column,
            y=spec.y_column,
            hue=spec.color_column,
            legend=(
                spec.color_column is not None
            ),
        )

    elif chart_type == "line":

        sns.lineplot(
            data=df,
            x=spec.x_column,
            y=spec.y_column,
            hue=spec.color_column,
        )

    elif chart_type == "scatter":

        sns.scatterplot(
            data=df,
            x=spec.x_column,
            y=spec.y_column,
            hue=spec.color_column,
        )

    elif chart_type == "pie":

        plt.pie(
            df[spec.y_column],
            labels=df[spec.x_column],
            autopct="%1.1f%%",
        )

    elif chart_type == "histogram":

        sns.histplot(
            data=df,
            x=spec.x_column,
        )

    elif chart_type == "box":

        sns.boxplot(
            data=df,
            x=spec.x_column,
            y=spec.y_column,
            hue=spec.color_column,
        )

    else:

        raise ValueError(
            f"Unsupported chart type: {chart_type}"
        )

    plt.title(spec.title)
    plt.xticks(rotation=45)
    plt.tight_layout()

    output_path = (
        OUTPUT_DIR / "visualization.png"
    )

    plt.savefig(
        output_path,
        dpi=150,
        bbox_inches="tight",
    )

    plt.close()

    return str(output_path)

# ============================================================
#  Render node
# ============================================================

def render_visualization_node(
    state: VisualizationState,
) -> dict:

    print(f"\nrender_visualization_node: {state}")

    path = render_visualization(
        state["dataframe"],
        VisualizationSpec.model_validate(state["visualization_spec"]),
    )

    return {
        "visualization_path": path,
        "dataframe": None
    }


# ============================================================
#  Build visualization specialist graph
# ============================================================

builder = StateGraph(
    VisualizationState
)

builder.add_node(
    "generate_sql",
    generate_sql_node,
)

builder.add_node(
    "execute_sql",
    execute_sql_node,
)

builder.add_node(
    "generate_visualization_spec",
    generate_visualization_spec_node,
)

builder.add_node(
    "validate_visualization_spec",
    validate_visualization_spec,
)

builder.add_node(
    "render_visualization",
    render_visualization_node,
)

builder.add_edge(
    START,
    "generate_sql",
)

builder.add_edge(
    "generate_sql",
    "execute_sql",
)

builder.add_edge(
    "execute_sql",
    "generate_visualization_spec",
)

builder.add_edge(
    "generate_visualization_spec",
    "validate_visualization_spec",
)

builder.add_edge(
    "validate_visualization_spec",
    "render_visualization",
)

builder.add_edge(
    "render_visualization",
    END,
)

# Use the custom serializer for Pandas DataFrame
checkpointer = InMemorySaver(serde=CustomSerializer())
visualization_graph = builder.compile(checkpointer=checkpointer)

def main():
    print("\ngraph built\n")
    print(visualization_graph.get_graph().draw_ascii())

    config1 = {
            "configurable": {
                "thread_id": "experiment-1" 
            }
    }

    result = visualization_graph.invoke(
        {
            "user_question":
                "Show me the top 10 countries by COVID-19 deaths."
        },
        config = config1
    )

    print(f"\nFinal result from visualization_graph.invoke: {result}")

    print("\nSQL:")
    print(result["sql"])

    print("\nVisualization spec:")
    print(result["visualization_spec"])

    print("\nImage:")
    print(result["visualization_path"])

if __name__ == "__main__":
    main()
