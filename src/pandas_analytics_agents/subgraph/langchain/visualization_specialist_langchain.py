# Custom serializer for Pandas DataFrame to survive checkpointing
class CustomSerializer(SerializerProtocol):
    """Custom serializer that handles Pandas DataFrame objects."""

    def dumps_typed(self, obj: Any) -> tuple[str, bytes]:
        if isinstance(obj, pd.DataFrame):
            # Use DataFrame.to_json() which is the supported API
            return "DataFrame", obj.to_json(orient="split").encode("utf-8")
        # Fall back to standard JSON for other types
        return "json", json.dumps(obj).encode("utf-8")

    def loads_typed(self, data: tuple[str, bytes]) -> Any:
        type_str, bytes_data = data
        if type_str == "DataFrame":
            # Reconstruct DataFrame from the JSON string
            json_str = bytes_data.decode("utf-8")
            return pd.read_json(json_str, orient="split")
        return json.loads(bytes_data.decode("utf-8"))


def execute_covid_sql(sql: str) -> pd.DataFrame:
    """
    Execute a read-only SQL query against the covid_19 dataset.

    This is an internal application function, NOT an LLM tool.
    """

    sql_clean = sql.strip()

    if not sql_clean.lower().startswith("select"):
        raise ValueError(
            "Only SELECT statements are allowed."
        )

    return get_df_from_sql_clean(sql_clean, None)


# ============================================================
#  Visualization specification
# ============================================================

class VisualizationSpec(BaseModel):
    """
    Declarative description of a visualization.

    The LLM generates this object.
    The application renders it deterministically.
    """

    chart_type: Literal[
        "bar",
        "line",
        "scatter",
        "pie",
        "histogram",
        "box",
    ] = Field(
        description="Type of chart to generate."
    )

    x_column: str | None = Field(
        default=None,
        description="Column used for the x-axis or category."
    )

    y_column: str | None = Field(
        default=None,
        description="Column used for the y-axis or numeric value."
    )

    color_column: str | None = Field(
        default=None,
        description="Optional column used to group/color the data."
    )

    title: str = Field(
        description="Human-readable chart title."
    )


# ============================================================
#  LangGraph state
# ============================================================

class VisualizationState(TypedDict, total=False):

    # Original user request.
    user_question: str

    # SQL generated by the first LLM stage.
    sql: str

    # Data retrieved from DuckDB.
    dataframe: pd.DataFrame | None

    # Human-readable description of the dataframe supplied
    # to the second LLM stage.
    dataframe_context: str

    # Visualization specification generated by the second
    # LLM stage.
    visualization_spec: dict #VisualizationSpec

    # Final image path.
    visualization_path: str

    # Error information if something fails.
    error: str


