SQL_SYSTEM_PROMPT = """
You are the SQL generation component of a data visualization
system.

Your job is to translate the user's visualization request into
ONE read-only DuckDB SQL SELECT statement against the table:

    covid_19

The table contains the COVID-19 dataset, which has the following columns:

Data columns (total 15 columns):
 #   Column                  Non-Null Count  Dtype  
---  ------                  --------------  -----  
 0   country                 187 non-null    str    
 1   Confirmed               187 non-null    int64  
 2   deaths                  187 non-null    int64  
 3   recovered               187 non-null    int64  
 4   Active                  187 non-null    int64  
 5   New cases               187 non-null    int64  
 6   New deaths              187 non-null    int64  
 7   New recovered           187 non-null    int64  
 8   Deaths / 100 Cases      187 non-null    float64
 9   Recovered / 100 Cases   187 non-null    float64
 10  Deaths / 100 Recovered  187 non-null    float64
 11  Confirmed last week     187 non-null    int64  
 12  1 week change           187 non-null    int64  
 13  1 week % increase       187 non-null    float64
 14  WHO Region              187 non-null    str    

 
Generate SQL only.

Rules:

1. Only generate SELECT statements. Do NOT generate any comments or explanations.
2. Do not modify data.
3. Do not use INSERT, UPDATE, DELETE, DROP, ALTER, CREATE,
   COPY, ATTACH, or other side-effecting statements.
4. Select only the columns necessary for the requested
   visualization.
5. If the user asks for "top N", use ORDER BY and LIMIT.
6. Make the result reasonably sized for visualization.
7. Do not generate matplotlib, seaborn, or Python code.

The SQL should produce exactly the dataset needed by the
visualization.
"""


def generate_sql_node(
    state: VisualizationState,
) -> dict:

    response = llm.invoke(
        [
            SystemMessage(
                content=SQL_SYSTEM_PROMPT
            ),
            HumanMessage(
                content=state["user_question"]
            ),
        ]
    )
    
    sql = getattr(response, "text", None) or getattr(response, "content", None) or ""

    print(f"\nsql node response text: {sql}")
    sql = sql.strip()

    # Remove accidental markdown fences.
    if sql.startswith("```"):
        lines = sql.splitlines()

        if lines[0].startswith("```"):
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        sql = "\n".join(lines).strip()

    return {
        "sql": sql
    }


# ============================================================
#  Execute SQL node
# ============================================================

def execute_sql_node(
    state: VisualizationState,
) -> dict:

    print(f"\nexecute_sql_node: {state}")

    try:
        df = execute_covid_sql(
            state["sql"]
        )

        if df.empty:
            raise ValueError(
                "The SQL query returned no rows."
            )

        print("\nexecute_sql_node: dataframe retrieved=>")
        print(df.info())
        print(df.head())
        return {
            "dataframe": df,
        }

    except Exception as exc:

        return {
            "error": (
                f"SQL execution failed: {exc}"
            )
        }


# ============================================================
#  Prepare DataFrame context
# ============================================================

def prepare_dataframe_context(
    df: pd.DataFrame,
) -> str:

    dtypes = "\n".join(
        f"- {column}: {dtype}"
        for column, dtype in df.dtypes.items()
    )

    sample = df.head(20).to_string(
        index=False
    )

    return f"""
Columns:

{dtypes}

Number of rows: {len(df)}

Sample rows:

{sample}
""".strip()


